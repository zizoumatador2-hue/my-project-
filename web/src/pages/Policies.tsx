        <li><strong>النقل الموجَّه:</strong> ست خطوات بالترتيب، لكل منها طرف منفّذ وطرف مؤكِّد: تجهيز الحساب وإزالة 2FA، تغيير بريد الاسترداد، تغيير الهاتف، تسليم كلمة المرور بكشف لمرة واحدة، تأكيد المشتري للدخول، ثم اعتماد فريق العمليات.</li>
